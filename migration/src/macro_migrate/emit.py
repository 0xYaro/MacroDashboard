"""Write the seed SQL.

Every statement is an idempotent upsert on the table's natural key, per
CONTRACT.md's "Every write is an idempotent upsert on a natural key. Replaying a
run is always safe." Rows are emitted in a fixed sort order and every id is a
uuid5, so two runs over unchanged sources produce byte-identical files.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from collections import defaultdict

from . import config
from .model import Build
from .textutil import (series_ref, sql_bool, sql_date, sql_int, sql_int_array,
                       sql_jsonb, sql_num, sql_str, sql_text_array, sql_ts)

HEADER = """\
-- {name}
-- Generated by migration/ (macro-migrate). Do not edit by hand: edit the
-- migration and re-run it. Re-running produces byte-identical output.
--
-- Source: the Obsidian vault's 3 - Work/31 - Macro history, read-only.
-- Verified by hand against migration/VERIFICATION.md.
"""

PREFLIGHT = """\
-- Preflight. config/series.yaml is authoritative for series keys and the worker
-- seeds macro_core.series from it. This block fails the load loudly if a key
-- this seed references is not present, so a renamed key can never load as a
-- silent null.
DO $$
DECLARE missing text;
BEGIN
  SELECT string_agg(k, ', ' ORDER BY k) INTO missing
  FROM (SELECT unnest(ARRAY[{keys}]) AS k) w
  WHERE NOT EXISTS (SELECT 1 FROM macro_core.series s WHERE s.key = w.k);
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'macro_core.series is missing keys referenced by the '
                    'migrated history: %', missing;
  END IF;
END $$;
"""


def _ins(table: str, cols: list[str], values: list[str], conflict: str,
         update: list[str]) -> str:
    sets = ",\n    ".join("%s = EXCLUDED.%s" % (c, c) for c in update)
    body = "INSERT INTO %s (%s)\nVALUES (%s)\nON CONFLICT (%s) DO " % (
        table, ", ".join(cols), ", ".join(values), conflict)
    body += ("UPDATE SET\n    " + sets) if update else "NOTHING"
    return body + ";"


def _file(path: Path, name: str, chunks: list[str], preflight_keys=None) -> None:
    out = [HEADER.format(name=name), ""]
    if preflight_keys:
        out.append(PREFLIGHT.format(
            keys=", ".join(sql_str(k) for k in sorted(preflight_keys))))
        out.append("")
    out.extend(chunks)
    path.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")


def emit(b: Build) -> list[Path]:
    out = config.OUT
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    # ---------------------------------------------------------------- series
    # config/series.yaml is authoritative. This file is a reconciliation report,
    # not a mapping to be applied: it lists every key this seed references, the
    # journal label it was read from, and any series.yaml key the migrated
    # history carries no observation for.
    used = sorted({o["series_key"] for o in b.rows.get("observation", [])})
    target_keys = sorted({r["series_key"] for r in b.rows.get("scenario_target", [])
                          if r["series_key"]})
    labels: dict[str, list[str]] = {}
    for o in b.rows.get("observation", []):
        labels.setdefault(o["series_key"], [])
        if o["_label"] not in labels[o["series_key"]]:
            labels[o["series_key"]].append(o["_label"])
    yaml_keys = set(config.SERIES_YAML_ROWS)
    p = out / "series_reconciliation.json"
    p.write_text(json.dumps({
        "series_yaml": str(config.SERIES_YAML.relative_to(config.REPO)),
        "series_yaml_present": config.SERIES_YAML.exists(),
        "series_yaml_keys": len(yaml_keys),
        "keys_with_migrated_observations": len(used),
        "keys_referenced_by_a_scenario_target": target_keys,
        "series_yaml_keys_with_no_migrated_observation":
            sorted(yaml_keys - set(used)),
        "keys_this_seed_references_that_series_yaml_lacks":
            sorted((set(used) | set(target_keys)) - yaml_keys),
        "journal_labels_per_key": {k: labels[k] for k in used},
        "journal_rows_not_imported": config.UNMAPPED_LABELS,
    }, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    written.append(p)

    all_series_keys = set(used) | set(target_keys)


    # -------------------------------------------------------------- judgment
    chunks: list[str] = []
    life = ["status", "authored_at", "activated_at", "superseded_by"]

    chunks.append(
        "-- phase_call: one per asset per week, four conditions each.\n"
        "-- 0005_core_constraints.sql makes the four-conditions rule a DEFERRABLE\n"
        "-- INITIALLY DEFERRED constraint trigger that fires at COMMIT, so a call\n"
        "-- and its conditions are written inside one transaction and the check\n"
        "-- never sees a half-built call.")
    conds = defaultdict(list)
    for c in b.rows.get("phase_condition", []):
        conds[c["phase_call_id"]].append(c)
    for r in sorted(b.rows.get("phase_call", []), key=lambda r: (r["week"], r["asset"])):
        chunks.append("BEGIN;")
        chunks.append(_ins(
            "macro_core.phase_call",
            ["id", "asset", "week", "phase", "phase_name", "prior_phase",
             "direction", "reason", "evidence", "falsifier"] + life,
            [sql_str(r["id"]), sql_str(r["asset"]), sql_str(r["week"]),
             sql_int(r["phase"]), sql_str(r["phase_name"]), sql_int(r["prior_phase"]),
             sql_str(r["direction"]), sql_str(r["reason"]),
             sql_text_array(r["evidence"]), sql_str(r["falsifier"]),
             sql_str(r["status"]), sql_ts(r["authored_at"]), sql_ts(r["activated_at"]),
             "NULL"],
            "id",
            ["phase", "phase_name", "prior_phase", "direction", "reason",
             "evidence", "falsifier"] + life))
        for c in sorted(conds[r["id"]], key=lambda c: c["ordinal"]):
            chunks.append(_ins(
                "macro_core.phase_condition",
                ["id", "phase_call_id", "ordinal", "text", "kind", "expr"],
                [sql_str(c["id"]), sql_str(c["phase_call_id"]), sql_int(c["ordinal"]),
                 sql_str(c["text"]), sql_str(c["kind"]), sql_jsonb(c["expr"])],
                "phase_call_id, ordinal", ["text", "kind", "expr"]))
        chunks.append("COMMIT;\n")

    chunks.append(
        "-- scenario_set, scenario, trigger_clause, scenario_target.\n"
        "-- Three scenarios summing to 100 is the other deferred constraint\n"
        "-- trigger, so a whole set is written inside one transaction.")
    scen = defaultdict(list)
    for x in b.rows.get("scenario", []):
        scen[x["set_id"]].append(x)
    clauses = defaultdict(list)
    for x in b.rows.get("trigger_clause", []):
        clauses[x["scenario_id"]].append(x)
    tgts = defaultdict(list)
    for x in b.rows.get("scenario_target", []):
        tgts[x["scenario_id"]].append(x)
    for r in sorted(b.rows.get("scenario_set", []), key=lambda r: r["week"]):
        chunks.append("BEGIN;")
        chunks.append(_ins(
            "macro_core.scenario_set",
            ["id", "week", "synthesis", "probability_check", "swing_variables",
             "rules_waived"] + life,
            [sql_str(r["id"]), sql_str(r["week"]), sql_str(r["synthesis"]),
             sql_str(r["probability_check"]), sql_jsonb(r["swing_variables"]),
             sql_int_array(r["rules_waived"]),
             sql_str(r["status"]), sql_ts(r["authored_at"]), sql_ts(r["activated_at"]),
             "NULL"],
            "id", ["synthesis", "probability_check", "swing_variables",
                   "rules_waived"] + life))
        for x in sorted(scen[r["id"]], key=lambda x: x["ordinal"]):
            chunks.append(_ins(
                "macro_core.scenario",
                ["id", "set_id", "ordinal", "title", "probability", "positioning"],
                [sql_str(x["id"]), sql_str(x["set_id"]), sql_int(x["ordinal"]),
                 sql_str(x["title"]), sql_int(x["probability"]),
                 sql_str(x["positioning"])],
                "set_id, ordinal", ["title", "probability", "positioning"]))
            for c in sorted(clauses[x["id"]], key=lambda c: c["ordinal"]):
                chunks.append(_ins(
                    "macro_core.trigger_clause",
                    ["id", "scenario_id", "ordinal", "text", "kind", "expr",
                     "catalyst_id", "required", "void_at", "void_reason"],
                    [sql_str(c["id"]), sql_str(c["scenario_id"]), sql_int(c["ordinal"]),
                     sql_str(c["text"]), sql_str(c["kind"]), sql_jsonb(c["expr"]),
                     sql_str(c["catalyst_id"]), sql_bool(c["required"]),
                     sql_ts(c["void_at"]), sql_str(c["void_reason"])],
                    "scenario_id, ordinal",
                    ["text", "kind", "expr", "catalyst_id", "required"]))
            for t in tgts[x["id"]]:
                chunks.append(_ins(
                    "macro_core.scenario_target",
                    ["id", "scenario_id", "series_id", "label", "kind", "comparator",
                     "lo", "hi", "text"],
                    [sql_str(t["id"]), sql_str(t["scenario_id"]),
                     series_ref(t["series_key"]) if t["series_key"] else "NULL",
                     sql_str(t["label"]), sql_str(t["kind"]), sql_str(t["comparator"]),
                     sql_num(t["lo"]), sql_num(t["hi"]), sql_str(t["text"])],
                    "id", ["series_id", "label", "kind", "comparator", "lo", "hi",
                           "text"]))
        chunks.append("COMMIT;\n")

    chunks.append("\n-- strategy, sector_focus, holdings_check.")
    for r in sorted(b.rows.get("strategy", []), key=lambda r: (r["week"], r["asset"])):
        chunks.append(_ins(
            "macro_core.strategy",
            ["id", "week", "asset", "stance", "posture", "exposure_lo",
             "exposure_hi", "exposure_operated_lo", "exposure_operated_hi"] + life,
            [sql_str(r["id"]), sql_str(r["week"]), sql_str(r["asset"]),
             sql_str(r["stance"]), sql_str(r["posture"]), sql_num(r["exposure_lo"]),
             sql_num(r["exposure_hi"]), sql_num(r["exposure_operated_lo"]),
             sql_num(r["exposure_operated_hi"]),
             sql_str(r["status"]), sql_ts(r["authored_at"]), sql_ts(r["activated_at"]),
             "NULL"],
            "id", ["stance", "posture", "exposure_lo", "exposure_hi",
                   "exposure_operated_lo", "exposure_operated_hi"] + life))
    for r in b.rows.get("sector_focus", []):
        chunks.append(_ins(
            "macro_core.sector_focus",
            ["id", "strategy_id", "band", "text"],
            [sql_str(r["id"]), sql_str(r["strategy_id"]), sql_str(r["band"]),
             sql_str(r["text"])],
            "strategy_id, band", ["text"]))
    for r in b.rows.get("holdings_check", []):
        chunks.append(_ins(
            "macro_core.holdings_check",
            ["id", "strategy_id", "ticker", "action", "text", "sector_focus_id"],
            [sql_str(r["id"]), sql_str(r["strategy_id"]), sql_str(r["ticker"]),
             sql_str(r["action"]), sql_str(r["text"]), sql_str(r["sector_focus_id"])],
            "strategy_id, ticker", ["action", "text", "sector_focus_id"]))

    chunks.append(
        "\n-- The supersession chain, linked after every row exists.\n"
        "-- superseded_by points forward to the row that replaced this one, so it\n"
        "-- cannot be set on insert: the successor is written later in the file.\n"
        "-- The lifecycle CHECK allows a superseded row to carry any successor and\n"
        "-- forbids an active one from carrying any, which is why only the rows\n"
        "-- before 2026-W39 appear here.")
    for table, rows in (("phase_call", b.rows.get("phase_call", [])),
                        ("scenario_set", b.rows.get("scenario_set", [])),
                        ("strategy", b.rows.get("strategy", []))):
        for r in sorted(rows, key=lambda r: (r["week"], r.get("asset", ""))):
            if r["superseded_by"]:
                chunks.append(
                    "UPDATE macro_core.%s SET superseded_by = %s WHERE id = %s;"
                    % (table, sql_str(r["superseded_by"]), sql_str(r["id"])))

    f = out / "10_judgment.sql"
    _file(f, "macro_core judgment for 2026-W32 to 2026-W39", chunks,
          preflight_keys=target_keys)
    written.append(f)

    # ------------------------------------------------------------ week_grade
    chunks = ["-- The Scorecard Ledger, one row per graded week, 2026-W23 onward.",
              "-- base_scenario_id is null for every week whose scenario set was "
              "not migrated.",
              "-- base_scenario_label always carries the title and probability as "
              "written."]
    for r in sorted(b.rows.get("week_grade", []), key=lambda r: r["week"]):
        chunks.append(_ins(
            "macro_core.week_grade",
            ["week", "base_scenario_id", "base_scenario_label", "base_grade",
             "other_grades", "eq_call", "crypto_call", "key_miss", "targets_hit",
             "targets_n", "brier", "premise_moved", "graded_at"],
            [sql_str(r["week"]), sql_str(r["base_scenario_id"]),
             sql_str(r["base_scenario_label"]), sql_str(r["base_grade"]),
             sql_jsonb(r["other_grades"]), sql_str(r["eq_call"]),
             sql_str(r["crypto_call"]), sql_str(r["key_miss"]),
             sql_int(r["targets_hit"]), sql_int(r["targets_n"]), sql_num(r["brier"]),
             sql_bool(r["premise_moved"]), sql_ts(r["graded_at"])],
            "week",
            ["base_scenario_id", "base_scenario_label", "base_grade",
             "other_grades", "eq_call", "crypto_call", "key_miss", "targets_hit",
             "targets_n", "brier", "premise_moved", "graded_at"]))
    f = out / "20_week_grade.sql"
    _file(f, "macro_core.week_grade", chunks)
    written.append(f)

    # --------------------------------------------------------- scenario_rule
    chunks = ["-- R1 to R12 and their teaching weeks. Numbers are never reused.",
              "-- Each teaching week is a real foreign key onto a graded week, so "
              "the app can count how many times a rule has fired."]
    for r in sorted(b.rows.get("scenario_rule", []), key=lambda r: r["number"]):
        chunks.append(_ins(
            "macro_core.scenario_rule", ["number", "text", "retired_week"],
            [sql_int(r["number"]), sql_str(r["text"]), sql_str(r["retired_week"])],
            "number", ["text", "retired_week"]))
    for r in sorted(b.rows.get("scenario_rule_week", []),
                    key=lambda r: (r["rule_number"], r["week"])):
        chunks.append(_ins(
            "macro_core.scenario_rule_week", ["rule_number", "week"],
            [sql_int(r["rule_number"]), sql_str(r["week"])],
            "rule_number, week", []))
    f = out / "30_scenario_rule.sql"
    _file(f, "macro_core.scenario_rule and scenario_rule_week", chunks)
    written.append(f)

    # ----------------------------------------------------------------- setup
    chunks = ["-- The Setup Ledger from 2026-W35, plus the setups the "
              "bootstrapped weeks proposed before the ledger begins."]
    for r in sorted(b.rows.get("setup", []), key=lambda r: (r["week"], r["asset"], r["name"])):
        chunks.append(_ins(
            "macro_core.setup",
            ["id", "week", "asset", "name", "style", "entry_lo", "entry_hi",
             "invalidation", "invalidation_dir", "target", "rr_planned",
             "gate_expr", "gate_text", "sector_focus_id", "series_id",
             "rationale"] + life,
            [sql_str(r["id"]), sql_str(r["week"]), sql_str(r["asset"]),
             sql_str(r["name"]), sql_str(r["style"]), sql_num(r["entry_lo"]),
             sql_num(r["entry_hi"]), sql_num(r["invalidation"]),
             sql_str(r["invalidation_dir"]), sql_num(r["target"]),
             sql_num(r["rr_planned"]), sql_jsonb(r["gate_expr"]),
             sql_str(r["gate_text"]), sql_str(r["sector_focus_id"]),
             series_ref(r["series_key"]) if r.get("series_key") else "NULL",
             sql_str(r["rationale"]),
             sql_str(r["status"]), sql_ts(r["authored_at"]), sql_ts(r["activated_at"]),
             sql_str(r["superseded_by"])],
            "id",
            ["week", "asset", "name", "style", "entry_lo", "entry_hi",
             "invalidation", "invalidation_dir", "target", "rr_planned",
             "gate_expr", "gate_text", "sector_focus_id", "series_id",
             "rationale"] + life))
    for r in sorted(b.rows.get("setup_grade", []), key=lambda r: r["setup_id"]):
        chunks.append(_ins(
            "macro_core.setup_grade",
            ["setup_id", "graded_week", "outcome", "r_realised", "note"],
            [sql_str(r["setup_id"]), sql_str(r["graded_week"]), sql_str(r["outcome"]),
             sql_num(r["r_realised"]), sql_str(r["note"])],
            "setup_id", ["graded_week", "outcome", "r_realised", "note"]))
    f = out / "40_setup.sql"
    # A setup names the series its levels are on, so this file references
    # macro_core.series and takes the same preflight as every other file that
    # does: a renamed key fails the load rather than loading as a silent null,
    # which for series_id is indistinguishable from a setup that names none.
    _file(f, "macro_core.setup and setup_grade", chunks,
          preflight_keys={r["series_key"] for r in b.rows.get("setup", [])
                          if r.get("series_key")})
    written.append(f)

    # ----------------------------------------------------------- observation
    chunks = ["-- The observation history the migrated snapshots carry.",
              "-- One row per series per observation date, dated in the source's "
              "own market calendar.",
              "-- HY and IG option-adjusted spreads are stored in basis points."]
    obs = sorted(b.rows.get("observation", []),
                 key=lambda r: (r["series_key"], r["asof"] or "", r["_week"]))
    for r in obs:
        chunks.append(_ins(
            "macro_core.observation",
            ["series_id", "asof", "value", "display", "tier", "source",
             "released", "note", "extra", "observed_at", "received_at"],
            [series_ref(r["series_key"]), sql_date(r["asof"]), sql_num(r["value"]),
             sql_str(r["display"]), sql_int(r["tier"]), sql_str(r["source"]),
             sql_date(r["released"]), sql_str(r["note"]), sql_jsonb(r["extra"]),
             sql_ts(r["observed_at"]), sql_ts(r["received_at"])],
            "series_id, asof",
            ["value", "display", "tier", "source", "released", "note", "extra",
             "observed_at", "received_at"]))
    f = out / "50_observation.sql"
    _file(f, "macro_core.observation", chunks,
          preflight_keys=all_series_keys)
    written.append(f)

    # -------------------------------------------- condition_state_asserted
    # The status a manual condition was written with. macro_mart.condition_state
    # is recomputable and would destroy an asserted status on its next rebuild,
    # so it lives in macro_core beside the judgment it belongs to.
    chunks = [
        "-- Every migrated phase condition and trigger clause is kind=manual, so",
        "-- no status can ever be computed for it. A phase tracker row carries the",
        "-- status the journal wrote (met, not yet, failed). A trigger clause does",
        "-- not: the grading journals judge a trigger as a whole, so every migrated",
        "-- clause is `unevaluable` and carries that whole-trigger verdict as its",
        "-- current_text. CONTRACT.md: a condition that cannot be evaluated is",
        "-- unevaluable, never `not yet`.",
    ]
    for r in sorted(b.rows.get("condition_state_asserted", []),
                    key=lambda r: (r["owner_kind"], r["_week"], r["_subject"])):
        chunks.append(_ins(
            "macro_core.condition_state_asserted",
            ["condition_id", "owner_kind", "status", "current_text",
             "asserted_at", "asserted_by"],
            [sql_str(r["condition_id"]), sql_str(r["owner_kind"]),
             sql_str(r["status"]), sql_str(r["current_text"]),
             sql_ts(r["asserted_at"]), sql_str(r["asserted_by"])],
            "condition_id",
            ["owner_kind", "status", "current_text", "asserted_at", "asserted_by"]))
    f = out / "60_condition_state.sql"
    _file(f, "macro_core.condition_state_asserted", chunks)
    written.append(f)

    # ------------------------------------------------------------ load order
    f = out / "load.sql"
    f.write_text(
        "-- Load order. Run against the macro_core schema after\n"
        "-- supabase/migrations has created it and config/series.yaml has been\n"
        "-- seeded into macro_core.series.\n"
        "\\i 10_judgment.sql\n"
        "\\i 20_week_grade.sql\n"
        "\\i 30_scenario_rule.sql\n"
        "\\i 40_setup.sql\n"
        "\\i 50_observation.sql\n"
        "\\i 60_condition_state.sql\n", encoding="utf-8")
    written.append(f)

    # -------------------------------------------------------------- manifest
    man = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
           for p in written if p.name != "manifest.json"}
    f = out / "manifest.json"
    f.write_text(json.dumps(man, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    written.append(f)
    return written
