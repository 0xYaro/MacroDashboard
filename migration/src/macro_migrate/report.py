"""VERIFICATION.md: the hand-verification report.

docs/DECISIONS.md requires this history be "verified by hand".
A reader cannot do that against 300 INSERT statements, so this file states, for
every migrated week, which source was read, how many rows of each table it
produced, and every field the source did not carry.

One sentence per line, because that is how the rest of this repository's
markdown is written and it makes a diff of this report legible.
"""
from __future__ import annotations

from collections import defaultdict

from . import config
from .model import Build
from .verify import (CONTRACT_ISSUES, Check, KNOWN_SOURCE_DEFECTS,
                     W39_CALIBRATION_SENTENCE)

TABLES_BY_WEEK = [
    ("phase_call", "week"), ("phase_condition", None),
    ("scenario_set", "week"), ("scenario", None), ("trigger_clause", None),
    ("scenario_target", None), ("strategy", "week"), ("sector_focus", None),
    ("holdings_check", None), ("setup", "week"), ("setup_grade", None),
    ("condition_state_asserted", "_week"), ("observation", "_week"),
]


def _week_counts(b: Build) -> dict[str, dict[str, int]]:
    out: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    week_of_call = {r["id"]: r["week"] for r in b.rows.get("phase_call", [])}
    week_of_set = {r["id"]: r["week"] for r in b.rows.get("scenario_set", [])}
    week_of_scen = {r["id"]: week_of_set[r["set_id"]]
                    for r in b.rows.get("scenario", [])}
    week_of_strat = {r["id"]: r["week"] for r in b.rows.get("strategy", [])}
    week_of_setup = {r["id"]: r["week"] for r in b.rows.get("setup", [])}
    for r in b.rows.get("phase_call", []):
        out[r["week"]]["phase_call"] += 1
    for r in b.rows.get("phase_condition", []):
        out[week_of_call[r["phase_call_id"]]]["phase_condition"] += 1
    for r in b.rows.get("scenario_set", []):
        out[r["week"]]["scenario_set"] += 1
    for r in b.rows.get("scenario", []):
        out[week_of_set[r["set_id"]]]["scenario"] += 1
    for r in b.rows.get("trigger_clause", []):
        out[week_of_scen[r["scenario_id"]]]["trigger_clause"] += 1
    for r in b.rows.get("scenario_target", []):
        out[week_of_scen[r["scenario_id"]]]["scenario_target"] += 1
    for r in b.rows.get("strategy", []):
        out[r["week"]]["strategy"] += 1
    for r in b.rows.get("sector_focus", []):
        out[week_of_strat[r["strategy_id"]]]["sector_focus"] += 1
    for r in b.rows.get("holdings_check", []):
        out[week_of_strat[r["strategy_id"]]]["holdings_check"] += 1
    for r in b.rows.get("setup", []):
        out[r["week"]]["setup"] += 1
    for r in b.rows.get("setup_grade", []):
        out[week_of_setup[r["setup_id"]]]["setup_grade"] += 1
    for r in b.rows.get("condition_state_asserted", []):
        out[r["_week"]]["condition_state_asserted"] += 1
    for r in b.rows.get("observation", []):
        out[r["_week"]]["observation"] += 1
    for r in b.rows.get("week_grade", []):
        out[r["week"]]["week_grade"] += 1
    return out


def _findings_by_week(b: Build) -> dict[str, list[tuple[str, list[str]]]]:
    """Group findings so that one sentence repeated over forty rows prints once."""
    grouped: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for f in b.findings:
        grouped[f.week][f.sentence].append(f.subject)
    out: dict[str, list[tuple[str, list[str]]]] = {}
    for week, by_sentence in grouped.items():
        out[week] = sorted(
            ((s, sorted(set(subs))) for s, subs in by_sentence.items()),
            key=lambda kv: (-len(kv[1]), kv[0]))
    return out


def _subjects(subs: list[str], limit: int = 6) -> str:
    if len(subs) <= limit:
        return ", ".join("`%s`" % s for s in subs)
    return ", ".join("`%s`" % s for s in subs[:limit]) + \
        " and %d more" % (len(subs) - limit)


def render(b: Build, checks: list[Check], calibration: dict,
           files: list) -> str:
    L: list[str] = []
    a = L.append
    counts = _week_counts(b)
    findings = _findings_by_week(b)
    failed = [c for c in checks if not c.passed]
    known = [c for c in checks if "KNOWN SOURCE DEFECT" in c.detail]

    a("# Verification")
    a("")
    a("This is the hand-verification report `docs/DECISIONS.md` asks for when it "
      "says the migrated history is \"verified by hand\".")
    a("It states, for every migrated week, which source was read, how many rows "
      "of each table that produced, and every field the source did not carry.")
    a("Nothing in it is written by hand: it is regenerated with the seed files, "
      "so it can never drift from them.")
    a("")
    a("Generated by `uv run macro-migrate build`.")
    a("Sources are read-only; nothing in this migration writes into the vault.")
    a("")

    # ---------------------------------------------------------------- headline
    a("## The calibration reproduction")
    a("")
    a("This is the single check the migration stands or falls on.")
    a("The 2026-W39 journal's section 0 prints a calibration sentence computed "
      "by `calibration.py` over `Scorecard Ledger.md`.")
    a("The migrated `macro_core.week_grade` rows, run through the same "
      "arithmetic over the database columns, must reproduce it exactly.")
    a("")
    a("Expected, as the journal prints it:")
    a("")
    a("> " + W39_CALIBRATION_SENTENCE)
    a("")
    a("Produced from `macro_core.week_grade`:")
    a("")
    a("> " + calibration["line"])
    a("")
    ok = calibration["line"] == W39_CALIBRATION_SENTENCE
    a("**%s**" % ("PASS, character for character." if ok else "FAIL."))
    a("")
    a("| Quantity | Value | Where it comes from |")
    a("| --- | --- | --- |")
    a("| graded weeks in the window | %d | the last 8 `week_grade` rows by week, "
      "%s to %s |" % (calibration["graded_weeks"], calibration["first_week"],
                      calibration["last_week"]))
    a("| base hit score | %.1f | `base_grade`, Materialized 1 and Partial 0.5 |"
      % calibration["base_hit_score"])
    a("| fully materialized | %d of %d | `base_grade = 'Materialized'` |"
      % (calibration["base_materialized"], calibration["graded_weeks"]))
    a("| mean Brier | %.3f over %d weeks | `brier`, which is null before "
      "2026-W36 |" % (calibration["mean_brier"], calibration["brier_weeks"]))
    a("| base was S2 | %d of %d | `base_scenario_label` beginning `S2` |"
      % (calibration["base_was_s2"], calibration["graded_weeks"]))
    a("")
    a("The `base_scenario_label` column is what makes this work over migrated "
      "rows: it carries the title and probability as the ledger wrote them, so "
      "the S2 habit check reads the same whether the scenario set was imported "
      "or not.")
    a("")

    # ----------------------------------------------------------------- oracles
    a("## Oracles")
    a("")
    a("%d checks, %d failed." % (len(checks), len(failed)))
    if known:
        a("%d passed against a recorded source defect, named in full below."
          % len(known))
    a("")
    a("| Check | Subject | Result | Detail |")
    a("| --- | --- | --- | --- |")
    for c in checks:
        verdict = "**FAIL**" if not c.passed else (
            "pass, source defect" if "KNOWN SOURCE DEFECT" in c.detail else "pass")
        a("| `%s` | %s | %s | %s |" % (
            c.key, c.subject, verdict,
            c.detail.replace("\n", " ").replace("|", "\\|")))
    a("")

    if known:
        a("### The one recorded denominator this migration does not match")
        a("")
        for (week, ordinal), reason in sorted(KNOWN_SOURCE_DEFECTS.items()):
            a("**%s S%d.** %s." % (week, ordinal, reason))
            a("")
        a("This is a discrepancy in the source, not a parse error, and the "
          "parse is deliberately not changed to match it.")
        a("")
        a("Both counts were written by the same grading block in the 2026-W37 "
          "journal, on opposite conventions.")
        a("It counted 2026-W36's S1 as **9**, which only reaches 9 by counting "
          "its three non-numeric legs (`Nasdaq leads`, `Russell lags`, `SOL "
          "leads`), and the journal's own prose enumerates all nine.")
        a("It counted 2026-W36's S2 as **6**, which only reaches 6 by excluding "
          "its two equivalent non-numeric legs (`ETH catches up`, `curve "
          "steepens`) from the eight the scenario states.")
        a("The two counts cannot both be right.")
        a("")
        a("This is the clearest evidence in the whole migration that "
          "`macro_core.scenario_target.kind` had to exist.")
        a("A leg like `curve steepens` is a stated forecast and belongs in the "
          "denominator, but it is not a band and can never be auto-scored, so "
          "counting it and machine-checking it are two different questions.")
        a("Before `kind`, a grader had to answer both with one number and "
          "answered them inconsistently inside a single block.")
        a("With `kind`, W36's S2 is 8 targets of which 6 are bands and 2 are "
          "manual, which is exactly the pair of numbers the journal was trying "
          "to express.")
        a("")
        a("The parse keeps all 8 stated legs, because dropping one would make "
          "the scenario look more checkable than it was.")
        a("2026-W36's S2 was not that week's base case, so the Scorecard "
          "Ledger's `6 of 9` for 2026-W36 is unaffected and `week_grade` is "
          "correct.")
        a("")

    # ------------------------------------------------------------- what we read
    a("## What was read")
    a("")
    a("| Source | Read |")
    a("| --- | --- |")
    a("| `Scorecard Ledger.md` | %d rows, 2026-W23 to 2026-W38 |"
      % b.read_log["Scorecard Ledger.md"]["rows"])
    a("| `Setup Ledger.md` | %d rows, 2026-W35 to 2026-W39 |"
      % b.read_log["Setup Ledger.md"]["rows"])
    a("| `scenario-rules.md` | %d rules, %d teaching weeks |"
      % (b.read_log["scenario-rules.md"]["rules"],
         b.read_log["scenario-rules.md"]["teaching_weeks"]))
    for week in config.JUDGMENT_WEEKS:
        o = b.read_log["origins"][week]
        a("| %s | %s |" % (week, o["origin"]))
    a("| `config/series.yaml` | %d series, used as the one source of keys and "
      "units |" % len(config.SERIES_YAML_ROWS))
    a("")
    a("Deliberately not read: the 2026-W03 to 2026-W31 archive, per "
      "`docs/DECISIONS.md`.")
    a("There is no 2026-W33 journal; the 2026-W32 scenario set was graded over "
      "two weeks and the Scorecard Ledger says so in its 2026-W32 row.")
    a("")

    # ------------------------------------------------------------ what we wrote
    a("## What was produced")
    a("")
    a("| File | Rows |")
    a("| --- | --- |")
    a("| `out/10_judgment.sql` | %d phase calls, %d phase conditions, %d "
      "scenario sets, %d scenarios, %d trigger clauses, %d scenario targets, "
      "%d strategies, %d sector-focus rows, %d holdings checks |" % (
          b.count("phase_call"), b.count("phase_condition"),
          b.count("scenario_set"), b.count("scenario"),
          b.count("trigger_clause"), b.count("scenario_target"),
          b.count("strategy"), b.count("sector_focus"),
          b.count("holdings_check")))
    a("| `out/20_week_grade.sql` | %d week grades |" % b.count("week_grade"))
    a("| `out/30_scenario_rule.sql` | %d rules, %d teaching weeks |"
      % (b.count("scenario_rule"), b.count("scenario_rule_week")))
    a("| `out/40_setup.sql` | %d setups, %d setup grades |"
      % (b.count("setup"), b.count("setup_grade")))
    a("| `out/50_observation.sql` | %d observation upserts over %d series |"
      % (b.count("observation"),
         len({o["series_key"] for o in b.rows["observation"]})))
    a("| `out/60_condition_state.sql` | %d asserted condition states: %d phase "
      "tracker rows and %d trigger clauses |" % (
          b.count("condition_state_asserted"),
          sum(1 for r in b.rows["condition_state_asserted"]
              if r["owner_kind"] == "phase"),
          sum(1 for r in b.rows["condition_state_asserted"]
              if r["owner_kind"] == "trigger")))
    a("")

    # -------------------------------------------------------------- per week
    a("## Week by week")
    a("")
    ledger_only = [r["week"] for r in b.rows["week_grade"]
                   if r["week"] not in config.JUDGMENT_WEEKS]
    a("### 2026-W23 to 2026-W31, the ledger-only weeks")
    a("")
    a("Read: the %d Scorecard Ledger rows for %s."
      % (len(ledger_only), ", ".join(ledger_only)))
    a("Produced: one `macro_core.week_grade` row each, and nothing else.")
    a("Their scenario sets, phase calls, setups and snapshots live in the "
      "2026-W03 to 2026-W31 archive, which is deliberately not imported.")
    a("")
    a("| Week | Base grade | Targets hit | Brier | base_scenario_id | graded_at |")
    a("| --- | --- | --- | --- | --- | --- |")
    for r in b.rows["week_grade"]:
        if r["week"] in config.JUDGMENT_WEEKS:
            continue
        a("| %s | %s | %s | %s | null | null |" % (
            r["week"], r["base_grade"],
            "%s of %s" % (r["targets_hit"], r["targets_n"])
            if r["targets_n"] else "null, the ledger carries `-`",
            r["brier"] if r["brier"] is not None
            else "null, the ledger carries `-`"))
    a("")
    seen_sentences: set[str] = set()
    lines: list[str] = []
    for w in ledger_only:
        for sentence, subs in findings.get(w, []):
            if sentence in seen_sentences:
                continue
            seen_sentences.add(sentence)
            lines.append("- %s" % sentence)
    if lines:
        a("Fields no source carried, for every one of these weeks:")
        a("")
        L.extend(lines)
        a("")

    for week in config.JUDGMENT_WEEKS:
        o = b.read_log["origins"][week]
        c = counts[week]
        a("### %s" % week)
        a("")
        a("Read: %s." % o["origin"])
        a("Authored as-of %s." % config.AUTHORED_ON.get(week, "unknown"))
        if o["repairs"]:
            for r in o["repairs"]:
                a("Repair applied to the text before parsing: %s." % r)
        if o["parser_issues"]:
            a("The parser reported: %s."
              % "; ".join(str(i) for i in o["parser_issues"]))
        a("")
        a("Produced: " + ", ".join(
            "%d %s" % (c[t], t) for t, _ in TABLES_BY_WEEK if c.get(t)) +
          (", %d week_grade" % c["week_grade"] if c.get("week_grade") else "") +
          ".")
        a("")
        grade = next((r for r in b.rows["week_grade"] if r["week"] == week), None)
        if grade:
            a("Graded by the %s journal on %s."
              % (grade["_graded_by"], grade["graded_at"]))
            a("Base case `%s`, graded %s, targets %s, Brier %s." % (
                grade["base_scenario_label"][:70], grade["base_grade"],
                "%s of %s" % (grade["targets_hit"], grade["targets_n"])
                if grade["targets_n"] else "not recorded before 2026-W36",
                grade["brier"] if grade["brier"] is not None
                else "not recorded before 2026-W36"))
            a("`base_scenario_id` %s." % (
                "points at the migrated scenario for this week"
                if grade["base_scenario_id"] else "is null"))
            a("")
        wf = findings.get(week, [])
        if wf:
            a("Fields the source did not carry, or values this migration had to "
              "decide:")
            a("")
            for sentence, subs in wf:
                a("- %s" % sentence)
                a("  Applies to: %s." % _subjects(subs))
            a("")

    # ------------------------------------------------------------- what is out
    a("## Deliberately not migrated")
    a("")
    a("- The 2026-W03 to 2026-W31 archive, per `docs/DECISIONS.md`. "
      "Those weeks exist in `week_grade` only.")
    a("- `macro_core.event`, `macro_core.catalyst`, `macro_core.holding`, "
      "`macro_core.watchlist_change` and `macro_core.tail_risk`. "
      "The sidecars carry an event log and a catalyst table, but the worker "
      "parses those from the three OpenClaw files on every run, and seeding "
      "them here would create a second writer for rows that are re-derived "
      "twice a day.")
    a("- Every `macro_mart` table. `macro_mart` is recomputed by the worker's "
      "evaluate step and this migration writes no derived row.")
    a("- `macro_core.series`. `config/series.yaml` is its one source.")
    for label, why in sorted(config.UNMAPPED_LABELS.items()):
        a("- The journal's `%s` snapshot row. %s" % (label, why))
    a("")

    a("## Contract and schema issues")
    a("")
    a("`docs/CONTRACT.md` is binding and this migration does not edit it.")
    a("Every disagreement found between the contract, "
      "`supabase/migrations/*.sql` and what the sources actually contain is "
      "listed here.")
    a("")
    for title, body in CONTRACT_ISSUES:
        a("### %s" % title)
        a("")
        for sentence in body.split(". "):
            sentence = sentence.strip()
            if sentence:
                a(sentence if sentence.endswith(".") else sentence + ".")
        a("")

    a("## Generated")
    a("")
    a("Files, with the sha256 the manifest records:")
    a("")
    a("| File | sha256 |")
    a("| --- | --- |")
    import hashlib
    for p in sorted(files, key=lambda p: p.name):
        if p.name == "manifest.json":
            continue
        a("| `out/%s` | `%s` |"
          % (p.name, hashlib.sha256(p.read_bytes()).hexdigest()[:16]))
    a("")
    a("Re-running the migration over unchanged sources reproduces these hashes "
      "byte for byte.")
    a("")
    return "\n".join(L) + "\n"
